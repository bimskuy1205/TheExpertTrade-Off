  function detectLang() {
    const p = new URLSearchParams(location.search).get("lang");
    if (p === "en" || p === "id") return p;
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "id") return saved;
    return "id";
  }

  let current = detectLang();

  function apply(lang) {
    current = lang === "en" ? "en" : "id";
    localStorage.setItem(STORAGE_KEY, current);
    document.documentElement.lang = current;
    const dict = DICT[current];

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const k = el.dataset.i18n;
      if (dict[k] !== undefined) el.textContent = dict[k];
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const k = el.dataset.i18nHtml;
      if (dict[k] !== undefined) el.innerHTML = dict[k];
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const k = el.dataset.i18nTitle;
      if (dict[k] !== undefined) el.title = dict[k];
    });
    document.querySelectorAll("[data-lang-pill]").forEach((el) => {
      el.dataset.lang = current;
      const a = el.querySelector("[data-l='id']");
      const b = el.querySelector("[data-l='en']");
      if (a) a.classList.toggle("on", current === "id");
      if (b) b.classList.toggle("on", current === "en");
    });

    if (document.body.dataset.page === "dash" && dict["meta.dash_title"]) {
      document.title = dict["meta.dash_title"];
    } else if (dict["meta.title"]) {
      document.title = dict["meta.title"];
    }

    // update glossary backing dictionary
    window.SYL = window.SYL || {};
    window.SYL.GLOSSARY = GLOSSARY[current];

    document.dispatchEvent(new CustomEvent("syl-lang-change", { detail: { lang: current } }));
  }

